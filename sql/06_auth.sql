CREATE TABLE hdk_users (
  user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR2(30)  NOT NULL,
  full_name     VARCHAR2(120) NOT NULL,
  email         VARCHAR2(150) NOT NULL,
  password_salt VARCHAR2(64)  NOT NULL,
  password_hash VARCHAR2(128) NOT NULL,
  role          VARCHAR2(10)  DEFAULT 'USER' NOT NULL,
  is_active     VARCHAR2(1)   DEFAULT 'Y' NOT NULL,
  created_on    DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT hdk_users_username_uk UNIQUE (username),
  CONSTRAINT hdk_users_email_uk    UNIQUE (email),
  CONSTRAINT hdk_users_role_ck     CHECK (role IN ('ADMIN', 'USER')),
  CONSTRAINT hdk_users_active_ck   CHECK (is_active IN ('Y', 'N'))
);

CREATE OR REPLACE PACKAGE hdk_auth_pkg AS

  c_app_id CONSTANT NUMBER := 198818;

  -- TRUE only while register_user runs, so the admin-only triggers let it through.
  g_registering BOOLEAN := FALSE;

  FUNCTION authenticate (p_username IN VARCHAR2, p_password IN VARCHAR2) RETURN BOOLEAN;
  FUNCTION current_username RETURN VARCHAR2;
  FUNCTION is_admin RETURN BOOLEAN;
  FUNCTION is_admin_yn RETURN VARCHAR2;
  PROCEDURE assert_admin;

  PROCEDURE register_user (
    p_username  IN VARCHAR2,
    p_full_name IN VARCHAR2,
    p_email     IN VARCHAR2,
    p_password  IN VARCHAR2,
    p_confirm   IN VARCHAR2
  );

END hdk_auth_pkg;
/

CREATE OR REPLACE PACKAGE BODY hdk_auth_pkg AS

  FUNCTION hash_password (p_salt IN VARCHAR2, p_password IN VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN apex_util.get_hash(apex_t_varchar2(p_salt, p_password), FALSE);
  END hash_password;

  FUNCTION authenticate (p_username IN VARCHAR2, p_password IN VARCHAR2) RETURN BOOLEAN IS
    l_salt   hdk_users.password_salt%TYPE;
    l_hash   hdk_users.password_hash%TYPE;
    l_active hdk_users.is_active%TYPE;
  BEGIN
    SELECT password_salt, password_hash, is_active
      INTO l_salt, l_hash, l_active
      FROM hdk_users
     WHERE username = LOWER(TRIM(p_username));

    RETURN l_active = 'Y' AND l_hash = hash_password(l_salt, p_password);
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN FALSE;
  END authenticate;

  FUNCTION current_username RETURN VARCHAR2 IS
  BEGIN
    RETURN LOWER(SYS_CONTEXT('APEX$SESSION', 'APP_USER'));
  END current_username;

  FUNCTION is_admin RETURN BOOLEAN IS
    l_role hdk_users.role%TYPE;
  BEGIN
    -- Access from outside this application (SQL Workshop, scripts, jobs) is not restricted.
    IF NVL(SYS_CONTEXT('APEX$SESSION', 'APP_ID'), '0') <> TO_CHAR(c_app_id) THEN
      RETURN TRUE;
    END IF;

    SELECT role INTO l_role
      FROM hdk_users
     WHERE username = current_username
       AND is_active = 'Y';
    RETURN l_role = 'ADMIN';
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN FALSE;
  END is_admin;

  FUNCTION is_admin_yn RETURN VARCHAR2 IS
  BEGIN
    RETURN CASE WHEN is_admin THEN 'Y' ELSE 'N' END;
  END is_admin_yn;

  PROCEDURE assert_admin IS
  BEGIN
    IF NOT g_registering AND NOT is_admin THEN
      RAISE_APPLICATION_ERROR(-20510, 'Only an administrator can do this.');
    END IF;
  END assert_admin;

  PROCEDURE register_user (
    p_username  IN VARCHAR2,
    p_full_name IN VARCHAR2,
    p_email     IN VARCHAR2,
    p_password  IN VARCHAR2,
    p_confirm   IN VARCHAR2
  ) IS
    l_username hdk_users.username%TYPE := LOWER(TRIM(p_username));
    l_email    hdk_users.email%TYPE    := LOWER(TRIM(p_email));
    l_salt     hdk_users.password_salt%TYPE;
    l_hash     hdk_users.password_hash%TYPE;
    l_count    NUMBER;
    l_role     hdk_users.role%TYPE;
  BEGIN
    IF l_username IS NULL OR NOT REGEXP_LIKE(l_username, '^[a-z0-9._]{3,30}$') THEN
      RAISE_APPLICATION_ERROR(-20501, 'Username must be 3 to 30 characters: letters, numbers, dot or underscore.');
    END IF;
    IF TRIM(p_full_name) IS NULL THEN
      RAISE_APPLICATION_ERROR(-20502, 'Please enter your full name.');
    END IF;
    IF l_email IS NULL OR NOT REGEXP_LIKE(l_email, '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') THEN
      RAISE_APPLICATION_ERROR(-20503, 'Please enter a valid email address.');
    END IF;
    IF p_password IS NULL OR LENGTH(p_password) < 8
       OR NOT REGEXP_LIKE(p_password, '[A-Za-z]') OR NOT REGEXP_LIKE(p_password, '[0-9]') THEN
      RAISE_APPLICATION_ERROR(-20504, 'Password must be at least 8 characters and include letters and numbers.');
    END IF;
    IF p_password <> p_confirm THEN
      RAISE_APPLICATION_ERROR(-20505, 'The two passwords do not match.');
    END IF;

    SELECT COUNT(*) INTO l_count FROM hdk_users WHERE username = l_username OR email = l_email;
    IF l_count > 0 THEN
      RAISE_APPLICATION_ERROR(-20506, 'An account with this username or email already exists.');
    END IF;

    -- The very first account becomes the administrator; everyone after that is a normal user.
    SELECT COUNT(*) INTO l_count FROM hdk_users;
    l_role := CASE WHEN l_count = 0 THEN 'ADMIN' ELSE 'USER' END;
    l_salt := RAWTOHEX(SYS_GUID()) || RAWTOHEX(SYS_GUID());
    l_hash := hash_password(l_salt, p_password);

    g_registering := TRUE;
    BEGIN
      INSERT INTO hdk_users (username, full_name, email, password_salt, password_hash, role)
      VALUES (l_username, TRIM(p_full_name), l_email, l_salt, l_hash, l_role);
    EXCEPTION
      WHEN OTHERS THEN
        g_registering := FALSE;
        RAISE;
    END;
    g_registering := FALSE;
  END register_user;

END hdk_auth_pkg;
/

-- Sign-up form target: the insert creates the account, then the table is emptied,
-- so no password is ever kept in this table.
CREATE TABLE hdk_register (
  reg_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username         VARCHAR2(30),
  full_name        VARCHAR2(120),
  email            VARCHAR2(150),
  password         VARCHAR2(100),
  confirm_password VARCHAR2(100)
);

CREATE OR REPLACE TRIGGER hdk_register_bi
  BEFORE INSERT ON hdk_register
  FOR EACH ROW
BEGIN
  hdk_auth_pkg.register_user(:NEW.username, :NEW.full_name, :NEW.email, :NEW.password, :NEW.confirm_password);
  :NEW.password         := NULL;
  :NEW.confirm_password := NULL;
END;
/

CREATE OR REPLACE TRIGGER hdk_register_ai
  AFTER INSERT ON hdk_register
BEGIN
  DELETE FROM hdk_register;
END;
/


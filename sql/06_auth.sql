-- Replaces the ticket trigger from 03_triggers.sql. A requester cannot choose the
-- status, agent or dates, and their details always come from their own account.
CREATE OR REPLACE TRIGGER hdk_tickets_biu
  BEFORE INSERT OR UPDATE ON hdk_tickets
  FOR EACH ROW
DECLARE
  l_name  hdk_users.full_name%TYPE;
  l_email hdk_users.email%TYPE;
BEGIN
  IF INSERTING THEN
    IF NOT hdk_auth_pkg.is_admin THEN
      :NEW.status      := 'NEW';
      :NEW.agent_id    := NULL;
      :NEW.created_on  := SYSDATE;
      :NEW.resolved_on := NULL;
      BEGIN
        SELECT full_name, email INTO l_name, l_email
          FROM hdk_users
         WHERE username = hdk_auth_pkg.current_username;
        :NEW.requester_name  := l_name;
        :NEW.requester_email := l_email;
      EXCEPTION
        WHEN NO_DATA_FOUND THEN NULL;
      END;
    END IF;

    :NEW.due_on := NVL(:NEW.due_on,
                       NVL(:NEW.created_on, SYSDATE) + hdk_ticket_pkg.sla_hours(:NEW.priority) / 24);
  ELSIF :OLD.status <> :NEW.status THEN
    IF NOT hdk_ticket_pkg.is_valid_transition(:OLD.status, :NEW.status) THEN
      RAISE_APPLICATION_ERROR(-20402,
        'A ticket cannot move from ' || :OLD.status || ' to ' || :NEW.status || '.');
    END IF;
  END IF;

  IF :NEW.status IN ('RESOLVED', 'CLOSED') THEN
    :NEW.resolved_on := NVL(:NEW.resolved_on, SYSDATE);
  ELSE
    :NEW.resolved_on := NULL;
  END IF;
END;
/

-- Replaces the ticket view from 04_views.sql: administrators see every ticket,
-- other users see only the tickets they raised.
CREATE OR REPLACE VIEW hdk_tickets_v AS
SELECT t.ticket_id,
       t.title,
       t.category,
       t.priority,
       t.status,
       t.requester_name,
       t.requester_email,
       t.agent_id,
       a.full_name AS agent_name,
       t.created_on,
       t.due_on,
       t.resolved_on,
       ROUND(NVL(t.resolved_on, SYSDATE) - t.created_on, 1) AS age_days,
       CASE WHEN t.status NOT IN ('RESOLVED', 'CLOSED') AND t.due_on < SYSDATE
            THEN 'Y' ELSE 'N' END AS is_overdue
  FROM hdk_tickets t
  LEFT JOIN hdk_agents a ON a.agent_id = t.agent_id
 WHERE hdk_auth_pkg.is_admin_yn = 'Y'
    OR LOWER(t.created_by) = hdk_auth_pkg.current_username;

-- Admin-only view for managing user roles and status.
CREATE OR REPLACE VIEW hdk_users_v (
  user_id, username, full_name, email, role, is_active, created_on,
  CONSTRAINT hdk_users_v_pk PRIMARY KEY (user_id) RELY DISABLE
) AS
SELECT user_id, username, full_name, email, role, is_active, created_on
  FROM hdk_users;

CREATE OR REPLACE TRIGGER hdk_users_v_iu
  INSTEAD OF UPDATE ON hdk_users_v
  FOR EACH ROW
BEGIN
  hdk_auth_pkg.assert_admin;
  UPDATE hdk_users
     SET full_name = :NEW.full_name,
         role      = :NEW.role,
         is_active = :NEW.is_active
   WHERE user_id = :OLD.user_id;
END;
/

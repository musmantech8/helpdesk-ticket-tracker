CREATE TABLE hdk_agents (
  agent_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name  VARCHAR2(120) NOT NULL,
  email      VARCHAR2(150) NOT NULL,
  is_active  VARCHAR2(1)   DEFAULT 'Y' NOT NULL,
  CONSTRAINT hdk_agents_email_uk  UNIQUE (email),
  CONSTRAINT hdk_agents_active_ck CHECK (is_active IN ('Y', 'N'))
);

CREATE TABLE hdk_tickets (
  ticket_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           VARCHAR2(200)  NOT NULL,
  description     VARCHAR2(2000),
  category        VARCHAR2(40)   DEFAULT 'General' NOT NULL,
  requester_name  VARCHAR2(120)  NOT NULL,
  requester_email VARCHAR2(150)  NOT NULL,
  priority        VARCHAR2(10)   DEFAULT 'MEDIUM' NOT NULL,
  status          VARCHAR2(12)   DEFAULT 'NEW' NOT NULL,
  agent_id        NUMBER         REFERENCES hdk_agents (agent_id),
  created_on      DATE           DEFAULT SYSDATE NOT NULL,
  due_on          DATE,
  resolved_on     DATE,
  created_by      VARCHAR2(100)  DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER),
  CONSTRAINT hdk_tickets_priority_ck CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
  CONSTRAINT hdk_tickets_status_ck   CHECK (status IN ('NEW', 'IN_PROGRESS', 'ON_HOLD', 'RESOLVED', 'CLOSED'))
);

CREATE INDEX hdk_tickets_agent_ix  ON hdk_tickets (agent_id);
CREATE INDEX hdk_tickets_status_ix ON hdk_tickets (status, priority);

CREATE TABLE hdk_comments (
  comment_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id    NUMBER         NOT NULL REFERENCES hdk_tickets (ticket_id),
  comment_text VARCHAR2(2000) NOT NULL,
  is_internal  VARCHAR2(1)    DEFAULT 'N' NOT NULL,
  created_on   DATE           DEFAULT SYSDATE NOT NULL,
  created_by   VARCHAR2(100)  DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER),
  CONSTRAINT hdk_comments_internal_ck CHECK (is_internal IN ('Y', 'N'))
);

CREATE INDEX hdk_comments_ticket_ix ON hdk_comments (ticket_id, created_on);

-- Written by the trigger HDK_TICKETS_AIU every time a ticket changes status.
CREATE TABLE hdk_status_history (
  history_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id   NUMBER        NOT NULL REFERENCES hdk_tickets (ticket_id),
  old_status  VARCHAR2(12),
  new_status  VARCHAR2(12)  NOT NULL,
  changed_on  DATE          DEFAULT SYSDATE NOT NULL,
  changed_by  VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER)
);

CREATE INDEX hdk_history_ticket_ix ON hdk_status_history (ticket_id, changed_on);
